import json

import pandas as pd
from sqlalchemy import inspect, text

from config import GROUND_TRUTH_DIR
from src.database.database import engine


EXPECTED_COUNTS = {
    "departments": 10,
    "skills": 50,
    "interviewers": 50,
    "candidates": 2000,
    "job_requisitions": 100,
    "applications": 3000,
    "interviews": 600,
    "offers": 150,
}


def run_validation():

    GROUND_TRUTH_DIR.mkdir(parents=True, exist_ok=True)

    results = []

    def add_result(check, status, details):
        results.append({
            "check": check,
            "status": status,
            "details": str(details)
        })

    inspector = inspect(engine)
    tables = inspector.get_table_names()

    print("\nRECRUITMENT DATA VALIDATION")
    print("=" * 60)

    with engine.connect() as connection:

        # -------------------------------------------------
        # 1. Database table existence
        # -------------------------------------------------
        add_result(
            "Database tables",
            "PASS" if tables else "FAIL",
            f"{len(tables)} tables found"
        )

        # -------------------------------------------------
        # 2. Primary key uniqueness
        # -------------------------------------------------
        for table in tables:

            primary_keys = inspector.get_pk_constraint(table).get(
                "constrained_columns", []
            )

            for column in primary_keys:

                query = text(
                    f'''
                    SELECT COUNT(*) FROM (
                        SELECT "{column}"
                        FROM "{table}"
                        GROUP BY "{column}"
                        HAVING COUNT(*) > 1
                    )
                    '''
                )

                duplicates = connection.execute(query).scalar()

                add_result(
                    f"Primary key uniqueness: {table}.{column}",
                    "PASS" if duplicates == 0 else "FAIL",
                    f"{duplicates} duplicate values"
                )

        # -------------------------------------------------
        # 3. Foreign key integrity
        # -------------------------------------------------
        fk_violations = connection.execute(
            text("PRAGMA foreign_key_check")
        ).fetchall()

        add_result(
            "Foreign key integrity",
            "PASS" if len(fk_violations) == 0 else "FAIL",
            f"{len(fk_violations)} foreign key violations"
        )

        # -------------------------------------------------
        # 4. Required field null checks
        # -------------------------------------------------
        for table in tables:

            columns = inspector.get_columns(table)

            for column in columns:

                if not column["nullable"] and column["default"] is None:

                    column_name = column["name"]

                    # Integer primary keys may be generated by SQLite.
                    if column_name in inspector.get_pk_constraint(
                        table
                    ).get("constrained_columns", []):
                        continue

                    query = text(
                        f'''
                        SELECT COUNT(*)
                        FROM "{table}"
                        WHERE "{column_name}" IS NULL
                        '''
                    )

                    null_count = connection.execute(query).scalar()

                    add_result(
                        f"Required values: {table}.{column_name}",
                        "PASS" if null_count == 0 else "FAIL",
                        f"{null_count} null values"
                    )

        # -------------------------------------------------
        # 5. Dataset record count checks
        # -------------------------------------------------
        for table, expected in EXPECTED_COUNTS.items():

            if table not in tables:
                add_result(
                    f"Record count: {table}",
                    "FAIL",
                    "Table does not exist"
                )
                continue

            actual = connection.execute(
                text(f'SELECT COUNT(*) FROM "{table}"')
            ).scalar()

            add_result(
                f"Record count: {table}",
                "PASS" if actual == expected else "WARNING",
                f"Expected {expected}, found {actual}"
            )

        # -------------------------------------------------
        # 6. Duplicate candidate-requisition applications
        # -------------------------------------------------
        if "applications" in tables:

            duplicates = connection.execute(text("""
                SELECT COUNT(*)
                FROM (
                    SELECT requisition_id, candidate_id
                    FROM applications
                    GROUP BY requisition_id, candidate_id
                    HAVING COUNT(*) > 1
                )
            """)).scalar()

            add_result(
                "Duplicate applications",
                "PASS" if duplicates == 0 else "FAIL",
                f"{duplicates} duplicate candidate-requisition pairs"
            )

        # -------------------------------------------------
        # 7. Salary range validation
        # -------------------------------------------------
        if {"offers", "applications", "job_requisitions"}.issubset(tables):

            offer_columns = {
                col["name"] for col in inspector.get_columns("offers")
            }

            salary_column = next(
                (
                    name for name in (
                        "offered_salary",
                        "salary",
                        "annual_salary",
                    )
                    if name in offer_columns
                ),
                None
            )

            if salary_column:

                violations = connection.execute(text(f"""
                    SELECT COUNT(*)
                    FROM offers o
                    JOIN applications a
                        ON o.application_id = a.id
                    JOIN job_requisitions r
                        ON a.requisition_id = r.id
                    WHERE o."{salary_column}" < r.minimum_salary
                       OR o."{salary_column}" > r.maximum_salary
                """)).scalar()

                add_result(
                    "Offer salary within approved range",
                    "PASS" if violations == 0 else "FAIL",
                    f"{violations} salary violations"
                )
            else:
                add_result(
                    "Offer salary within approved range",
                    "WARNING",
                    "Could not identify the offer salary column"
                )

        # -------------------------------------------------
        # 8. Interview date validation
        # -------------------------------------------------
        if "interviews" in tables:

            interview_columns = {
                col["name"] for col in inspector.get_columns("interviews")
            }

            if {"scheduled_start", "scheduled_end"}.issubset(
                interview_columns
            ):

                invalid_dates = connection.execute(text("""
                    SELECT COUNT(*)
                    FROM interviews
                    WHERE scheduled_end <= scheduled_start
                """)).scalar()

                add_result(
                    "Interview date consistency",
                    "PASS" if invalid_dates == 0 else "FAIL",
                    f"{invalid_dates} invalid interview time ranges"
                )

        # -------------------------------------------------
        # 9. Application and requisition relationships
        # -------------------------------------------------
        if {"applications", "job_requisitions"}.issubset(tables):

            missing_requisitions = connection.execute(text("""
                SELECT COUNT(*)
                FROM applications a
                LEFT JOIN job_requisitions r
                    ON a.requisition_id = r.id
                WHERE r.id IS NULL
            """)).scalar()

            add_result(
                "Application requisition relationships",
                "PASS" if missing_requisitions == 0 else "FAIL",
                f"{missing_requisitions} applications with missing requisitions"
            )

        # -------------------------------------------------
        # 10. Skill count range
        # -------------------------------------------------
        if "skills" in tables:

            skill_count = connection.execute(
                text("SELECT COUNT(*) FROM skills")
            ).scalar()

            add_result(
                "Skill count within target range",
                "PASS" if 30 <= skill_count <= 50 else "WARNING",
                f"Found {skill_count}; target is 30 to 50"
            )

    # -------------------------------------------------
    # Generate validation report
    # -------------------------------------------------
    dataframe = pd.DataFrame(results)

    report_path = GROUND_TRUTH_DIR / "validation_report.csv"

    dataframe.to_csv(report_path, index=False)

    passed = sum(r["status"] == "PASS" for r in results)
    failed = sum(r["status"] == "FAIL" for r in results)
    warnings = sum(r["status"] == "WARNING" for r in results)

    summary = {
        "project": "Recruitment Management & Analytics System",
        "total_checks": len(results),
        "passed": passed,
        "failed": failed,
        "warnings": warnings,
        "overall_status": (
            "FAILED" if failed else
            "PASSED_WITH_WARNINGS" if warnings else
            "PASSED"
        ),
        "results": results
    }

    summary_path = GROUND_TRUTH_DIR / "validation_summary.json"

    with open(summary_path, "w", encoding="utf-8") as file:
        json.dump(summary, file, indent=4)

    print("\nVALIDATION RESULTS")
    print("-" * 60)

    for result in results:
        print(
            f'{result["status"]:<8} '
            f'{result["check"]:<42} '
            f'{result["details"]}'
        )

    print("-" * 60)
    print("Total checks:", len(results))
    print("Passed:", passed)
    print("Failed:", failed)
    print("Warnings:", warnings)
    print("Overall status:", summary["overall_status"])

    print("\nReports generated:")
    print(report_path)
    print(summary_path)

    return summary


if __name__ == "__main__":
    run_validation()